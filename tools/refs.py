"""Strip the game assemblies the mod compiles against into reference assemblies for CI.

CI runs on GitHub's machines without the game, so the release workflow checks
out a private repo holding signature only copies of the DLLs that
NeutralQoL.csproj references (method bodies and private members removed by
JetBrains Refasmer, pinned in the repo's dotnet tool manifest). This writes
that repo's contents in the folder layout the build expects, so CI passes the
folder as -p:GamePath unchanged.

    python tools/refs.py --game-version 0.34.1 [--out ..\\NeutralQoL-refs] [--game PATH]

Re-run after every game update, then commit and push the refs repo.
"""
import argparse
import os
import re
import shutil
import subprocess
import sys

from gamepath import PROJECT, REPO, build_game_path, managed_dir


NOTICE = """# Reference assemblies, not the original game files

The DLLs in `NuclearOption_Data/Managed/` are NOT the original files from
Nuclear Option. They are reference assemblies generated by
`tools/refs.py` in NeutralQoL with JetBrains Refasmer, from game version
{version}:

- Every method body is removed, so they contain no game code or logic.
- Every private member is removed.
- Only the names and signatures of public types and members remain, which is
  what the C# compiler needs to build the mod.

They cannot run the game or be used in place of the originals. Their only
purpose is to let NeutralQoL's CI build on machines without the game.

The original assemblies and everything derived from them belong to their
owners: Shockfront Studios (Nuclear Option), Unity Technologies (Unity) and
Guavaman Enterprises (Rewired). This repository is private and must not be
made public, shared or redistributed.
"""


def referenced_dlls():
    with open(PROJECT, encoding='utf-8') as f:
        return re.findall(r'<Reference Include="\$\(ManagedPath\)[\\/]([^"]+\.dll)"', f.read())


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    ap.add_argument('--game-version', required=True,
                    help='game version these refs come from, e.g. 0.34.1 (CI writes it into the release manifest)')
    ap.add_argument('--out', default=os.path.join(os.path.dirname(REPO), 'NeutralQoL-refs'),
                    help='clone of the private refs repo (default ..\\NeutralQoL-refs)')
    ap.add_argument('--game', help='game install folder (default: the one dotnet build uses)')
    args = ap.parse_args()

    args.game = args.game or build_game_path()
    managed = managed_dir(args.game) if args.game else ''
    if not os.path.isdir(managed):
        sys.exit('game not found: run python tools/setup.py or pass --game')

    dlls = referenced_dlls()
    if not dlls:
        sys.exit(f'no $(ManagedPath) references in {PROJECT}')
    missing = [d for d in dlls if not os.path.isfile(os.path.join(managed, d))]
    if missing:
        sys.exit('missing in ' + managed + ': ' + ', '.join(missing))

    out_managed = managed_dir(args.out)
    # A DLL the csproj no longer references must not linger in the refs.
    shutil.rmtree(out_managed, ignore_errors=True)
    os.makedirs(out_managed)

    subprocess.run(['dotnet', 'tool', 'restore'], cwd=REPO, check=True, stdout=subprocess.DEVNULL)
    subprocess.run(['dotnet', 'refasmer', '-q', '--omit-non-api-members=true', '-O', out_managed]
                   + [os.path.join(managed, d) for d in dlls], cwd=REPO, check=True)

    with open(os.path.join(args.out, 'game-version.txt'), 'w', encoding='utf-8', newline='\n') as f:
        f.write(args.game_version + '\n')
    with open(os.path.join(args.out, 'NOTICE.md'), 'w', encoding='utf-8', newline='\n') as f:
        f.write(NOTICE.format(version=args.game_version))
    build_hash = os.path.join(args.game, 'build-hash.txt')
    if os.path.isfile(build_hash):
        shutil.copy(build_hash, os.path.join(args.out, 'build-hash.txt'))

    size = sum(os.path.getsize(os.path.join(out_managed, d)) for d in os.listdir(out_managed))
    print(f'{len(dlls)} reference assemblies ({size // 1024} KB) -> {out_managed}')
    print(f'commit and push {args.out} so CI builds against game {args.game_version}')


if __name__ == '__main__':
    main()
